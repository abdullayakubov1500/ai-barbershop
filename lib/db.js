import { neon } from "@neondatabase/serverless";
import { loadEnv } from "./loadEnv.js";
import { SERVICES, seedIfEmpty } from "./seed.js";

loadEnv();

let sql;
let ready;

export function getSql() {
  const url = String(process.env.DATABASE_URL || "").trim();
  if (!url) {
    throw new Error("DATABASE_URL пуст: укажите строку подключения Neon.");
  }
  if (!sql) {
    sql = neon(url);
  }
  return sql;
}

export async function getDb() {
  if (!ready) {
    ready = init();
  }
  await ready;
  return getSql();
}

async function init() {
  const db = getSql();
  await migrate(db);
  await seedIfEmpty(db);
  await syncLocalData(db);
}

async function migrate(db) {
  await db`CREATE TABLE IF NOT EXISTS barbers (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    specialty TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  await db`CREATE TABLE IF NOT EXISTS schedules (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    barber_id INTEGER NOT NULL REFERENCES barbers(id) ON DELETE CASCADE,
    weekday INTEGER NOT NULL,
    start_time TEXT,
    end_time TEXT,
    UNIQUE (barber_id, weekday)
  )`;
  await db`CREATE TABLE IF NOT EXISTS services (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    duration_min INTEGER NOT NULL,
    price INTEGER NOT NULL
  )`;
  await db`CREATE TABLE IF NOT EXISTS bookings (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    barber_id INTEGER NOT NULL REFERENCES barbers(id),
    service_id INTEGER NOT NULL REFERENCES services(id),
    date TEXT NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    source TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'booked',
    telegram_user_id TEXT,
    telegram_username TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  await db`CREATE INDEX IF NOT EXISTS idx_bookings_barber_date
    ON bookings (barber_id, date, status)`;
  await db`CREATE UNIQUE INDEX IF NOT EXISTS uniq_booked_slot
    ON bookings (barber_id, date, start_time)
    WHERE status = 'booked'`;
  await db`CREATE TABLE IF NOT EXISTS booking_reminders (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    booking_id INTEGER NOT NULL REFERENCES bookings(id),
    kind TEXT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (booking_id, kind)
  )`;
  await db`CREATE TABLE IF NOT EXISTS telegram_contacts (
    username TEXT PRIMARY KEY,
    telegram_user_id TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
}

async function syncLocalData(db) {
  for (const service of SERVICES) {
    await db`UPDATE services
      SET price = ${service.price}, duration_min = ${service.duration_min}
      WHERE name = ${service.name}`;
  }
  await db`UPDATE bookings
    SET client_phone = '+99890' || right(replace(client_phone, '+', ''), 7)
    WHERE client_phone LIKE '+7%'`;
}
